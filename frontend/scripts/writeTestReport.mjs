import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { stripVTControlCharacters } from "node:util";

const frontendDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryDir = resolve(frontendDir, "..");
const reportDir = resolve(repositoryDir, "reports/tests");
const junitPath = resolve(reportDir, "junit.xml");
const vitestEntry = resolve(frontendDir, "node_modules/vitest/vitest.mjs");

const redactPaths = (text) =>
  text
    .replaceAll(pathToFileURL(repositoryDir).href, "<repo>")
    .replaceAll(repositoryDir, "<repo>");

mkdirSync(reportDir, { recursive: true });

const run = spawnSync(
  process.execPath,
  [
    vitestEntry,
    "run",
    "--coverage",
    "--reporter=verbose",
    "--reporter=junit",
    `--outputFile.junit=${junitPath}`,
  ],
  { cwd: frontendDir, encoding: "utf8", env: { ...process.env, NO_COLOR: "1", CI: "1" } },
);

const junit = redactPaths(readFileSync(junitPath, "utf8")).replace(/ hostname="[^"]*"/g, "");
writeFileSync(junitPath, junit);

const header = [
  "Generated by: npm run test:report",
  `Generated at: ${new Date().toISOString()}`,
  `Node.js: ${process.version}`,
  `Exit code: ${run.status}`,
  "",
].join("\n");
writeFileSync(
  resolve(reportDir, "test-run.txt"),
  header + redactPaths(stripVTControlCharacters(`${run.stdout}${run.stderr}`)),
);

process.exit(run.status ?? 1);
